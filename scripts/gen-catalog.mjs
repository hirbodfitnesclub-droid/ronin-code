// Generates the catalog modules for server / host / gui from docs/model-catalog.json.
// Run: node scripts/gen-catalog.mjs   (re-run whenever the catalog JSON changes)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(fs.readFileSync(path.join(root, 'docs/model-catalog.json'), 'utf8'));
const models = src.models ?? src;
const economics = src.economics ?? {};
if (!Array.isArray(models) || models.length === 0) throw new Error('catalog has no models');

const header = '// GENERATED by scripts/gen-catalog.mjs from docs/model-catalog.json — do not edit by hand.\n';
const js = `${header}export const CATALOG = ${JSON.stringify(models, null, 2)};\n\nexport const ECONOMICS = ${JSON.stringify(economics, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'server/src/catalog.js'), js);
fs.writeFileSync(path.join(root, 'host/src/catalog.js'), js);

const ts = `${header}export interface CatalogModel {\n  id: string;\n  name: string;\n  family: string;\n  coeff: number;\n  fastCoeff?: number;\n  context: number;\n  inputs: string[];\n  efforts: string[];\n}\n\nexport const CATALOG: CatalogModel[] = ${JSON.stringify(models, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'gui/src/lib/catalog.ts'), ts);
console.log(`catalog: ${models.length} models → server/src/catalog.js, host/src/catalog.js, gui/src/lib/catalog.ts`);
